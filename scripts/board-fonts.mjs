// Extracts the glyphs Maya's board needs from an SVG font (single-line, open paths) into a TypeScript data file (#319).
// Usage: node scripts/board-fonts.mjs <font.svg> <out.ts> <EXPORT_NAME> "<Font name>" "<source note>"
// The output keeps each glyph's path data exactly as the font has it; src/lib/board/fonts.ts turns it into strokes.
// Keep the font's OFL.txt and credits next to the output (see src/lib/board/font-data/*/README.md).
import { readFileSync, writeFileSync } from "node:fs";

const [src, out, exportName, fontName, sourceNote] = process.argv.slice(2);
if (!src || !out || !exportName || !fontName || !sourceNote) {
  console.error('usage: node scripts/board-fonts.mjs <font.svg> <out.ts> <EXPORT_NAME> "<Font name>" "<source note>"');
  process.exit(1);
}

// Digits, school math signs, letters and the punctuation a short note needs. The minus (U+2212 and the hyphen) and the check mark are
// the board's own paths, never the font's.
const CHARS = [..."0123456789+×÷=.,()?!%:'/<>", ..."abcdefghijklmnopqrstuvwxyz", ..."ABCDEFGHIJKLMNOPQRSTUVWXYZ"];

const entities = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };
const unescape = (s) =>
  s.replace(/&(#x[0-9a-f]+|#[0-9]+|[a-z]+);/gi, (m, e) =>
    e[0] === "#" ? String.fromCodePoint(e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10)) : (entities[e] ?? m),
  );

const svg = readFileSync(src, "utf8");
const glyphs = new Map();
for (const [, attrs] of svg.matchAll(/<glyph\b([^>]*?)\/?>/gs)) {
  const unicode = attrs.match(/\bunicode="([^"]*)"/);
  if (!unicode) continue;
  const char = unescape(unicode[1]);
  const d = attrs.match(/\bd="([^"]*)"/s);
  if (!glyphs.has(char)) glyphs.set(char, d ? d[1].replace(/\s+/g, " ").trim() : "");
}

const missing = CHARS.filter((c) => !glyphs.has(c));
if (missing.length) console.warn(`${fontName}: no glyph for ${missing.join(" ")}`);
const lines = CHARS.filter((c) => glyphs.has(c)).map((c) => `    ${JSON.stringify(c)}: ${JSON.stringify(glyphs.get(c))},`);
writeFileSync(
  out,
  `// Generated by scripts/board-fonts.mjs from ${sourceNote}. Do not edit by hand.
// Font software under the SIL Open Font License 1.1: see OFL.txt and README.md in this folder.
import type { SvgFontData } from "@/lib/board/fonts";

export const ${exportName}: SvgFontData = {
  name: ${JSON.stringify(fontName)},
  glyphs: {
${lines.join("\n")}
  },
};
`,
);
console.log(`${fontName}: ${lines.length} glyphs -> ${out}`);
