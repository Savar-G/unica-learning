// Database checks: writes src/lib/database.checks.ts from the live schema of the Supabase project, schema public. It
// lists every check constraint, as Postgres prints it, so tests can compare each state list in the code with the
// values the database allows (src/lib/state-lists.test.ts). Run it after each migration that adds or changes a check,
// beside npm run db:types, and commit the file with the migration's PR. The file is only ever replaced whole.
//
// Usage: npm run db:checks
// It needs what db:types needs: the Supabase CLI and an access token (scripts/supabase-token.mjs: SUPABASE_ACCESS_TOKEN,
// then the Keychain item "supabase-pagewise", then the CLI's own login). The query only reads the catalog.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { KEYCHAIN_ITEM, PROJECT, supabaseToken } from "./supabase-token.mjs";

const OUT = new URL("../src/lib/database.checks.ts", import.meta.url);
const SQL = `select c.conrelid::regclass::text as table_name, c.conname as name, pg_get_constraintdef(c.oid) as definition
from pg_constraint c join pg_class t on t.oid = c.conrelid
where c.contype = 'c' and t.relnamespace = 'public'::regnamespace
order by 1, 2`;

const token = supabaseToken();
let answer;
try {
  answer = execFileSync("supabase", ["db", "query", "--linked", "--project-ref", PROJECT, "-o", "json", SQL], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    env: token ? { ...process.env, SUPABASE_ACCESS_TOKEN: token } : process.env,
  });
} catch (e) {
  console.error(`db:checks: the Supabase CLI failed. ${e.stderr?.trim() || e.stdout?.trim() || e.message}`);
  if (!token) console.error(`db:checks: no access token found. Store one in the Keychain item "${KEYCHAIN_ITEM}" (see scripts/supabase-token.mjs).`);
  process.exit(1);
}
let rows;
try {
  rows = JSON.parse(answer).rows;
} catch {
  rows = null;
}
const valid = Array.isArray(rows) && rows.length > 0
  && rows.every((r) => typeof r.table_name === "string" && typeof r.name === "string" && typeof r.definition === "string");
if (!valid) {
  console.error(`db:checks: the CLI answer is not the list of checks; src/lib/database.checks.ts is unchanged.\n${answer.slice(0, 500)}`);
  process.exit(1);
}
const checks = rows
  .map((r) => ({ table: r.table_name.replace(/^public\./, "").replace(/^"(.*)"$/, "$1"), name: r.name, definition: r.definition }))
  .sort((a, b) => (a.table === b.table ? (a.name < b.name ? -1 : 1) : a.table < b.table ? -1 : 1));
const body = checks.map((c) => `  ${JSON.stringify(c)},`).join("\n");
writeFileSync(OUT, `// Generated by npm run db:checks (scripts/db-checks.mjs) from the live schema, schema public. Do not edit by hand.
// Every check constraint as Postgres prints it. Read it through src/lib/database-checks.ts.
export const DATABASE_CHECKS: readonly { table: string; name: string; definition: string }[] = [
${body}
];
`);
console.log(`db:checks: wrote ${checks.length} checks to src/lib/database.checks.ts`);
