// The TypeScript allow-list is authoritative. Generate the additive SQL copy.
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
const compiled = buildSync({ entryPoints: ['src/lib/supported-time-zones.ts'], bundle: true, platform: 'node', format: 'esm', write: false });
const { SUPPORTED_TIME_ZONES, SQL_TIME_ZONE_RULES } = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const target = 'supabase/migrations/20261102172026_supported_family_zones.sql';
const previous = readFileSync('supabase/migrations/20261102164821_maya_window_zones.sql', 'utf8');
const zoneAt = previous.slice(previous.indexOf('create or replace function public._maya_zone_at'), previous.indexOf('-- Internal pure calculation.'))
  .replace('else p_zone end;', `else coalesce('${JSON.stringify(SQL_TIME_ZONE_RULES)}'::jsonb ->> p_zone, p_zone) end;`);
const sql = `-- Generated by scripts/generate-family-zones.mjs. Do not edit this file by hand.
-- Source: src/lib/supported-time-zones.ts. Unknown IDs use the family fallback.
create or replace function public._maya_normalize_zone(p_zone text) returns text
language sql immutable strict set search_path = '' as $$
  select case when p_zone ~ '^[A-Za-z][A-Za-z0-9_+/-]{0,63}$' then
    '${JSON.stringify(SUPPORTED_TIME_ZONES, null, 2)}'::jsonb ->> lower(p_zone)
  else null end;
$$;
revoke all on function public._maya_normalize_zone(text) from public, anon, authenticated, service_role;

${zoneAt}
-- The current deployed app may still write raw aliases. Normalize every database write too.
create or replace function public.normalize_parent_time_zone() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  new.time_zone := public._maya_normalize_zone(new.time_zone);
  return new;
end $$;
revoke all on function public.normalize_parent_time_zone() from public, anon, authenticated, service_role;
create or replace trigger normalize_parent_time_zone before insert or update of time_zone on public.parents
  for each row execute function public.normalize_parent_time_zone();

-- Touch only aliases and unsupported values. Canonical values and null stay untouched.
-- The live apply supplies an expected count in this transaction. Abort on a mismatch.
do $$
declare v_changed bigint; v_expected text;
begin
  update public.parents set time_zone = public._maya_normalize_zone(time_zone)
    where time_zone is distinct from public._maya_normalize_zone(time_zone);
  get diagnostics v_changed = row_count;
  v_expected := nullif(current_setting('unica.expected_time_zone_updates', true), '');
  if v_expected is not null and v_changed <> v_expected::bigint then
    raise exception 'family_zone_backfill_count_mismatch: expected %, changed %', v_expected, v_changed;
  end if;
  raise notice 'family_time_zones_canonicalized: %', v_changed;
end $$;
`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('SQL allow-list differs from TypeScript. Run npm run generate:family-zones.');
  console.log(`PASS generated SQL: ${Object.keys(SUPPORTED_TIME_ZONES).length} supported IDs`);
} else {
  writeFileSync(target, sql);
  console.log(`Generated ${target}`);
}
